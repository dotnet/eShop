"""Renders architecture-rules.md from the policy YAML. The Markdown is generated - never edit it by hand."""
from __future__ import annotations

from .policy import CHECKPOINTS, PolicyPack

CP_LABEL = {"pre_commit": "Pre-commit", "code_review": "Code review", "testing": "Testing", "ci": "CI/CD"}


def _cp(beh: dict) -> str:
    if not beh.get("enabled"):
        return "off"
    return f"{beh['enforcement']} ({beh.get('scope', 'default')})"


def _cell(text: str) -> str:
    # Escape '<' outside code spans so markdownlint (MD033) does not read generics like List<T> as inline HTML.
    parts = " ".join(str(text).split()).replace("|", "\\|").split("`")
    return "`".join(p if i % 2 else p.replace("<", "&lt;") for i, p in enumerate(parts)) or "-"


def _sep(cols: int) -> str:
    return "|" + " --- |" * cols


def render(pack: PolicyPack) -> str:
    m = pack.manifest
    rules = pack.active_rules()
    out: list[str] = []
    w = out.append
    w("<!-- GENERATED by 'python architecture-policy/hooks/arch.py docs' from rules/*.yaml, patterns/*.yaml,")
    w("     validators/registry.yaml and exceptions/exceptions.yaml. Do not edit by hand. -->")
    w("")
    w(f"# Architecture Rules - {m.get('name')} v{m.get('version')}")
    w("")
    w("The Architecture Policy Pack is the single source of truth for architecture governance. Every consumer "
      "(Git pre-commit, Review Agent, Test Agent, CI/CD) calls the same operations in `hooks/architecture`, "
      "which evaluate these rules with the validators listed below.")
    w("")
    w("```text")
    w("Pre-Commit   -> architecture.validate(pre_commit,  context, artifacts)")
    w("Review Agent -> architecture.validate(code_review, context, artifacts)")
    w("Test Agent   -> architecture.validate(testing,     context, artifacts)")
    w("CI/CD        -> architecture.validate(ci,          context, artifacts)")
    w("```")
    w("")
    w("## Decision model")
    w("")
    w("| Enforcement | Finding outcome | Effect |")
    w(_sep(3))
    w("| `block` | BLOCK | Decision BLOCK (exit 1) |")
    w("| `warn` | WARN | Decision WARN (exit 0, or 3 with `--strict`) |")
    w("| `advisory` | INFO | Reported only |")
    w("")
    w("- Decision precedence: **BLOCK > WARN > PASS**. Validator errors fail closed (treated as a failure at the rule's enforcement).")
    w("- Semantic validators never call an LLM. Without a recorded judgment they return `needs_review` "
      "(capped at WARN) plus a review request (rubric, questions, response shape) for the Review/Test Agent or a human.")
    w("- Required evidence missing at a checkpoint produces a finding with the evidence's `on_missing` outcome.")
    w(f"- Exceptions live only in `exceptions/exceptions.yaml`: scoped to one rule and path globs, max "
      f"{m['exceptions']['max_duration_days']} days, approver role by severity. Active exceptions turn findings into WAIVED; "
      "expired exceptions are enforced again and reported.")
    w("")
    w("## Summary")
    w("")
    w("| ID | Title | Severity | Mode | " + " | ".join(CP_LABEL[c] for c in CHECKPOINTS) + " | Human review |")
    w(_sep(5 + len(CHECKPOINTS)))
    for r in rules:
        w(f"| [{r['id']}](#{r['id'].lower()}) | {_cell(r['title'])} | {r['severity']} | {r['validation']['mode']} | "
          + " | ".join(_cp(r["checkpoints"][c]) for c in CHECKPOINTS)
          + f" | {'yes' if r['human_review_required'] else 'no'} |")
    w("")
    for cat in m["categories"]:
        cat_rules = [r for r in rules if r["category"] == cat["id"]]
        w(f"## {cat['id'].replace('_', ' ').title()} ({cat['prefix']})")
        w("")
        for r in cat_rules:
            w(f"### {r['id']}")
            w("")
            w(f"**{r['title']}** - severity `{r['severity']}`, owner `{r['owner']}`, v{r['version']}, "
              f"validation `{r['validation']['mode']}`{', **human review required**' if r['human_review_required'] else ''}")
            w("")
            w(_cell(r["description"]))
            w("")
            w(f"*Rationale:* {_cell(r['rationale'])}")
            w("")
            a = r["applicability"]
            w(f"*Applies to:* `{'`, `'.join(a['include'])}`"
              + (f"; excluding `{'`, `'.join(a['exclude'])}`" if a.get("exclude") else "")
              + (f"; project types: {', '.join(a['project_types'])}" if a.get("project_types") else "")
              + (f"; service traits: {', '.join(a['service_traits'])}" if a.get("service_traits") else ""))
            if a.get("note"):
                w(f" ({_cell(a['note'])})")
            w("")
            w("| Checkpoint | Behavior | Note |")
            w(_sep(3))
            for c in CHECKPOINTS:
                w(f"| {CP_LABEL[c]} | {_cp(r['checkpoints'][c])} | {_cell(r['checkpoints'][c].get('note', ''))} |")
            w("")
            vals = []
            for vid in r["validation"]["validators"]:
                v = pack.validators.get(vid, {})
                vals.append(f"`{vid}` ({v.get('type', '?')}, `{v.get('implementation', '?')}`)")
            w(f"*Validators:* {', '.join(vals)}")
            w("")
            sem = r["validation"].get("semantic")
            if sem:
                w(f"*Semantic rubric:* {_cell(sem['rubric'])}")
                w("")
                for q in sem.get("questions", []):
                    w(f"- {_cell(q)}")
                w("")
                w(f"*Pass criteria:* {_cell(sem['pass_criteria'])}")
                w("")
            if r.get("patterns"):
                w("*Approved patterns:* " + ", ".join(f"`{p}` ({pack.patterns[p]['name']})" if p in pack.patterns else f"`{p}`"
                                                    for p in r["patterns"]))
                w("")
            w("*Required evidence:* " + "; ".join(
                f"`{e['type']}` at {', '.join(e['checkpoints'])} (missing -> {e['on_missing']})" for e in r["required_evidence"]))
            w("")
            w(f"*Remediation:* {_cell(r['remediation']['summary'])}")
            w("")
            for s in r["remediation"].get("steps", []):
                w(f"1. {_cell(s)}")
            if r["remediation"].get("steps"):
                w("")
            excs = [e for e in pack.exceptions if e["rule_id"] == r["id"]]
            if excs:
                w("*Exceptions:* " + ", ".join(f"`{e['id']}` (expires {e['expires']})" for e in excs))
                w("")
    w("## Approved patterns")
    w("")
    w("| ID | Name | Category | Rules | Exemplars |")
    w(_sep(5))
    for pid, p in sorted(pack.patterns.items()):
        w(f"| `{pid}` | {_cell(p['name'])} | {p['category']} | {', '.join(p['rules'])} | "
          + "<br>".join(f"`{x['path']}`" for x in p.get("exemplars", [])) + " |")
    w("")
    w("## Validators")
    w("")
    w("| ID | Type | Implementation | Checkpoints | Self-tests |")
    w(_sep(5))
    for vid, v in sorted(pack.validators.items()):
        w(f"| `{vid}` | {v['type']} | `{v['implementation']}` | {', '.join(v['checkpoints'])} | {len(v.get('self_tests', []))} |")
    w("")
    w("## Exceptions register")
    w("")
    w("| ID | Rule | Scope | Approved by (role) | Created | Expires |")
    w(_sep(6))
    for e in pack.exceptions:
        w(f"| `{e['id']}` | {e['rule_id']} | {'<br>'.join('`' + p + '`' for p in e['scope']['paths'])} | "
          f"{e['approved_by']} ({e['approver_role']}) | {e['created']} | {e['expires']} |")
    w("")
    return "\n".join(out)
